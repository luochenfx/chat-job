-- 单个搜索组合的时间上限：默认值 1200 秒 -> 21600 秒。
--
-- 1200 秒（20 分钟）是按「每张卡几秒」估的，人类化交互上线后实际节奏是每张卡 40–60 秒
-- （滚动 → 进详情 → AI 判定 → 投递或跳过）。同一个搜索组合在 Boss 上最多能加载到 300 张，
-- 全部看完要 3–5 小时，于是每个组合每天都会被判成 COMBINATION_TIMEOUT，
-- 界面上的表现就是「扫了一会儿就停，剩下的岗位永远轮不到」。
--
-- 21600 秒 = 6 小时 = 300 张 × 60 秒（最慢的一档）再留 20% 余量。
--
-- 两件事必须一起做，缺一件就等于没改：
-- 1. 已有行：把仍停留在旧默认值 1200 的行改成 21600。不迁数据的话，代码里的新默认值
--    只对「新建平台配置行」生效，升级后现有两个平台仍然是 20 分钟超时。
-- 2. 新建行：由 ConfigStore.createPlatformConfig 显式写 DEFAULT_COMBINATION_TIME_LIMIT_SEC，
--    不依赖列的 DEFAULT。
--
-- 关于列默认值：SQLite 不支持 ALTER COLUMN ... SET DEFAULT，所以 V1 里那句
-- `DEFAULT 1200` 会一直留在表定义里。这是可接受的 —— 本项目的平台配置行一律经
-- ConfigStore 创建（显式设全部字段），没有绕过它的 INSERT。不要在 V1 上直接改，
-- 已应用的迁移被 Flyway 按整份文件校验和核对，改一个字符就会让已升级的库起不来。
--
-- 恰好手工填过 1200 的行也会被一起改成 21600。这是有意的：1200 就是旧默认值，
-- 没有人会主动挑这个数；真要精确控制，改完之后在配置页重填即可。
-- 0 与负数表示「不限时间」，不会被这条 UPDATE 碰到。
UPDATE platform_config SET combination_time_limit_sec = 21600 WHERE combination_time_limit_sec = 1200;
