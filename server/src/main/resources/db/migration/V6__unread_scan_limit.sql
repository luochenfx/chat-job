-- 未读列表扫描上限。原先写死在 BossAdapter.listUnreadThreads 里（Math.min(items.count(), 30)）。
--
-- 为什么必须可配置：聊天列表是整页渲染的，没有滚动加载，但真正的问题不在 DOM ——
-- 在于「只读前 30 条」既不报错也不打日志。列表长到 35 条时，排在后面的 5 个会话
-- 永远不会被扫到、不会被回复，从日志上完全看不出来。任务表（V5）解决的是
-- 「发现了但处理失败」，解决不了「压根没发现」。
--
-- 默认 100：全量读取的成本是每条 3 次跨进程 locator 调用（标题 / 摘要 / 未读徽标），
-- 100 条约 2~5 秒，相对 120s 一轮的值守间隔可以忽略；实测列表 35 条，留两倍余量。
-- 上限 500 由 ConfigStore 归一，防止列表异常膨胀时一轮值守吃掉整个扫描节奏。
ALTER TABLE platform_config ADD COLUMN unread_scan_limit INTEGER NOT NULL DEFAULT 100;
